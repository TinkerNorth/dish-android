# Usage: gen_controller_tables.py <controllers.json> <strings/en.json> <out header>
#
# Writes the compiled identity tables usb_parsers.cpp reads (kKnown, kImported, kBluetoothKnown)
# from the bundled controller database, so the tables and the data the app ships cannot drift.
# Run by both CMake builds (app/src/main/cpp and app/src/test/cpp) and by the Gradle task the
# JVM sync test reads. A record is placed by its verification state and transport:
#   transport bluetooth                  -> kBluetoothKnown (its identity.bluetooth ids)
#   transport usb, state verified        -> kKnown          (the verified fast lane)
#   transport usb, any other state       -> kImported       (recognised, Direct by opt-in)
# The row's name is controller.<id>.name from en.json; input.protocol.ref, output.init.kind and
# input.mapping map onto Parser, InitKind and ButtonOrder by docs/controller-db.md section 4.1.
# A family, init kind or mapping outside that vocabulary fails the build: the bundled copy is what
# this binary compiles, so it can only name what the binary has.

import json
import os
import sys

PARSER = {
    "xinput360": "XINPUT_360",
    "xinput360Wireless": "XINPUT_360_WIRELESS",
    "xboxOneGip": "XBOX_ONE_GIP",
    "dualshock4": "DUALSHOCK4",
    "dualsense": "DUALSENSE",
    "switchProUsb": "SWITCH_PRO_USB",
    "switchN64Usb": "SWITCH_N64_USB",
    "stadia": "STADIA",
    "hid": "GENERIC_HID_GAMEPAD",
    "steamController": "STEAM_CONTROLLER",
    "steamTriton": "STEAM_TRITON",
    "steamControllerBle": "STEAM_CONTROLLER_BLE",
}

INIT = {
    "none": "NONE",
    "xboxOnePowerOn": "XBOX_ONE_POWERON",
    "xboxOneS": "XBOX_ONE_S",
    "switchProHandshake": "SWITCH_PRO_HANDSHAKE",
    "steamQuiet": "STEAM_QUIET",
    "steamTritonQuiet": "STEAM_TRITON_QUIET",
}

ORDER = {
    "western": "WESTERN",
    "switch": "SWITCH",
    "eightbitdo": "EIGHTBITDO",
    "playstationClassic": "PLAYSTATION_CLASSIC",
}

HID_FAMILY = "hid"
DEFAULT_MAPPING = "western"


def fail(message):
    sys.stderr.write("gen_controller_tables: %s\n" % message)
    sys.exit(1)


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lookup(table, key, what, record_id):
    if key not in table:
        fail("record %s names an unknown %s %r" % (record_id, what, key))
    return table[key]


def row_of(identity, record, name):
    vid_text, pid_text = identity.split(":")
    family = record["input"]["protocol"]["ref"]
    parser = lookup(PARSER, family, "family", record["id"])
    init = lookup(INIT, record["output"]["init"]["kind"], "init kind", record["id"])
    mapping = record["input"].get("mapping", DEFAULT_MAPPING) if family == HID_FAMILY else DEFAULT_MAPPING
    order = lookup(ORDER, mapping, "mapping", record["id"])
    return "    {0x%s, 0x%s, %s, Parser::%s, InitKind::%s, ButtonOrder::%s}," % (
        vid_text.upper(),
        pid_text.upper(),
        c_string(name),
        parser,
        init,
        order,
    )


def tables_of(db, strings):
    known, imported, bluetooth = [], [], []
    for record in db["records"]:
        name_key = "controller.%s.name" % record["id"]
        if name_key not in strings:
            fail("record %s has no en name" % record["id"])
        name = strings[name_key]
        support = record["support"]["verification"]
        if support["transport"] == "bluetooth":
            bluetooth += [row_of(i, record, name) for i in record["identity"]["bluetooth"]]
            continue
        target = known if support["state"] == "verified" else imported
        target += [row_of(i, record, name) for i in record["identity"]["usb"]]
    return known, imported, bluetooth


def table_text(name, rows):
    return "inline constexpr KnownDevice %s[] = {\n%s\n};\n" % (name, "\n".join(rows))


def main():
    if len(sys.argv) != 4:
        fail("usage: gen_controller_tables.py <controllers.json> <strings/en.json> <out header>")
    with open(sys.argv[1], encoding="utf-8") as f:
        db = json.load(f)
    with open(sys.argv[2], encoding="utf-8") as f:
        strings = json.load(f)
    if db.get("schema") != 1:
        fail("controllers.json is schema %r, this build reads schema 1" % db.get("schema"))
    known, imported, bluetooth = tables_of(db, strings)
    header = (
        "// SPDX-License-Identifier: LGPL-3.0-or-later\n"
        "// Generated by scripts/gen_controller_tables.py from controllers.json dbVersion %d.\n"
        "// Do not edit: change the controller database and rebuild.\n\n"
        "#pragma once\n\n"
        '#include "usb_parsers.h"\n\n'
        "namespace usbparsers {\n\n"
        "inline constexpr int kGeneratedDbVersion = %d;\n\n"
        "%s\n%s\n%s\n"
        "} // namespace usbparsers\n"
    ) % (
        db["dbVersion"],
        db["dbVersion"],
        table_text("kKnown", known),
        table_text("kImported", imported),
        table_text("kBluetoothKnown", bluetooth),
    )
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[3])), exist_ok=True)
    with open(sys.argv[3], "w", encoding="utf-8") as f:
        f.write(header)


if __name__ == "__main__":
    main()
